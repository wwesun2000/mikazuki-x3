"""Reproduce ScenePack effect 22's production function bodies with the pinned upstream PS2Recomp CLI."""
import argparse
from collections import Counter
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import struct
import tempfile
from time import perf_counter

import run_ps2recomp_pilot as pilot

ROOT = pilot.ROOT
WORK = ROOT / 'local/pc-core/ps2recomp-expandband'
ARCHIVE = ROOT / 'analysis/ps2recomp-expandband'
HEADER = ROOT / 'port/core/expandband_generated.hpp'
SETTERS = (0x179c40, 0x179c48, 0x179c58, 0x179c68)
EFFECT = (0x184690, 0x184760, 0x1847a8, 0x1848b8)
ENTRIES = SETTERS + EFFECT
INSTRUCTION = re.compile(rb'^\s*// 0x([0-9a-f]+): 0x([0-9a-f]{1,8})\b', re.I | re.M)


def save(path, data):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        f.write(data)
        scratch = Path(f.name)
    scratch.replace(path)


def hash_bytes(data):
    return hashlib.sha256(data).hexdigest()


def pack(run, elapsed):
    generated = json.loads((run/'generated.json').read_bytes())
    elf = (run/'SLPM_664.52').read_bytes()
    if hash_bytes(elf) != pilot.ELF_SHA:
        raise ValueError('Boot ELF changed')
    upstream_header = (run/'generated/ps2_recompiled_functions.h').read_bytes()
    declarations = []
    bodies = []
    functions = []
    nonlocal_destinations = set()
    word_rows = io.StringIO(newline='')
    writer = csv.writer(word_rows)
    writer.writerow(('function','va','elf_offset','original_word','emitted_comments'))
    for address in ENTRIES:
        f = generated['functions'][hex(address)]
        full_path = run/f['source']
        source = full_path.read_bytes()
        digest = hash_bytes(source)
        if digest != f['source_sha256']:
            raise ValueError('Upstream output changed after generation')
        start = source.index(b'// Function: ')
        body = source[start:]
        fn = re.search(rb'^void (\w+)\([^\r\n]+?\) \{\r?$', body, re.M)
        decl = re.search(rb'^void '+fn[1]+rb'\([^\r\n]+?\);\r?$', upstream_header, re.M)
        if not decl or fn[0].rstrip().removesuffix(b' {') != decl[0].rstrip()[:-1]:
            raise ValueError(f'Upstream ABI declaration mismatch at {address:#x}')
        declarations.append(decl[0].rstrip(b'\r')+b'\n')
        bodies.append(body)
        limit = int(f['end_exclusive'],16)
        offset = f['elf_file_offset']
        if hash_bytes(elf[offset:offset+limit-address]) != f['original_bytes_sha256']:
            raise ValueError('Original function block differs from the generation record')
        comments = Counter()
        for va_text, word_text in INSTRUCTION.findall(body):
            va, word = int(va_text,16), int(word_text,16)
            if not address<=va<limit or va%4 or struct.unpack_from('<I',elf,offset+va-address)[0] != word:
                raise ValueError(f'Generated comment differs from retail instruction at {va:#x}')
            comments[va] += 1
        missing=sorted(set(range(address,limit,4))-comments.keys())
        if any(struct.unpack_from('<I',elf,offset+va-address)[0]!=0 for va in missing):
            raise ValueError(f'Incomplete instruction provenance at {address:#x}')
        jumps = []
        for va in range(address,limit,4):
            off = offset+va-address
            word, = struct.unpack_from('<I',elf,off)
            writer.writerow((hex(address),hex(va),hex(off),f'{word:08x}',comments[va]))
            if word >> 26 in (2,3):
                target = ((va+4)&0xf0000000)|((word&0x03ffffff)<<2)
                if not address<=target<limit:
                    jumps.append({'pc':hex(va),'kind':'jal' if word>>26==3 else 'j','target':hex(target)})
                    nonlocal_destinations.add(target)
        dest = ARCHIVE/'generated'/full_path.name
        save(dest,source)
        functions.append({'entry':hex(address), 'end_exclusive':hex(limit), 'elf_file_offset':offset,
            'original_bytes_sha256':f['original_bytes_sha256'], 'original_words':(limit-address)//4,
            'upstream_omitted_zero_word_comments':[hex(va) for va in missing],
            'raw_cpp':dest.relative_to(ROOT).as_posix(), 'raw_cpp_sha256':digest,
            'unchanged_body_byte_offset':start, 'unchanged_body_bytes':len(body), 'unchanged_body_sha256':hash_bytes(body),
            'generated_signature':decl[0].decode().strip(),'original_external_j_jal':jumps,
            'literal_guest_dispatch_targets':sorted(set(re.findall(r'dispatchGuestBranch\(rdram, ctx, (0x[0-9A-F]+)u', body.decode())))})
    header = (b'// Generated by tools/generate_expandband_recomp.py. Source ranges and hashes: analysis/ps2recomp-expandband/manifest.json\n'
              b'#pragma once\n\n'+b''.join(declarations)+b'\n'+b'\n'.join(bodies))
    save(HEADER,header)
    save(ARCHIVE/'instruction-words.csv',word_rows.getvalue().encode('ascii'))
    for name in ('functions.csv','recompile.toml','recompile.log'):
        save(ARCHIVE/name,(run/name).read_bytes())
    warnings = [line.strip() for line in (run/'recompile.log').read_text(encoding='utf-8').splitlines() if '[warning]' in line]
    report={'status':'upstream_function_bodies_generated','iso_sha256':generated['iso_sha256'],
        'boot_elf_sha256':pilot.ELF_SHA,'upstream_repository':'https://github.com/ran-j/PS2Recomp',
        'upstream_commit':generated['upstream_commit'],'generator_executable_sha256':generated['generator_sha256'],
        'function_map_sha256':generated['ghidra_map_sha256'],'config_sha256':generated['config_sha256'],
        'header':HEADER.relative_to(ROOT).as_posix(),'header_sha256':hash_bytes(header),
        'instruction_map_sha256':pilot.sha(ARCHIVE/'instruction-words.csv'),
        'selected_effect_functions_generated':len(EFFECT),'selected_leaf_functions_generated':len(SETTERS),
        'selected_manually_translated_function_bodies':0,'unique_original_instruction_words':sum(f['original_words'] for f in functions),
        'generated_body_bytes':sum(f['unchanged_body_bytes'] for f in functions),
        'packaging':'Declarations copied from the upstream header, bodies copied byte-for-byte from each upstream .cpp beginning at its function comment. Includes are supplied by the host translation unit.',
        'manual_boundary':'CPU and device interface, allocation, task dispatch, GS submission and rendering lie outside the above generated-body count.',
        'original_distinct_j_jal_targets_outside_generated_bodies':[hex(a) for a in sorted(nonlocal_destinations-set(ENTRIES))],
        'upstream_warnings':warnings,
        'warning_scope':'CLI processes the original boot entry and constructors for registration. Its boot-entry control-flow warnings must be retained; the boot entry is not in the product effect header.',
        'scope':'Compilation and runtime differential evidence are separate from generator provenance.',
        'functions':functions}
    save(ARCHIVE/'manifest.json',(json.dumps(report,indent=2)+'\n').encode())
    pilot.record(run/'production-export.json',dict(total_generate_seconds=elapsed,
                 output_header_sha256=report['header_sha256'], functions=len(ENTRIES)))
    timing=ARCHIVE/'generation-timing.json'
    if not timing.exists() or json.loads(timing.read_bytes())['header_sha256']!=report['header_sha256']:
        pilot.record(timing,dict(header_sha256=report['header_sha256'],run_directory=str(run),
                     measured_seconds=elapsed,measurement='Elapsed wall time: ISO hash, ELF extraction, Ghidra map load, unmodified upstream CLI, result verification. Excludes host adapter and compilation.'))
    print(f'{HEADER}: {len(functions)} unchanged upstream function definitions, {report["unique_original_instruction_words"]} original instruction words')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--iso',type=Path,default=ROOT/'Kamaitachi no Yoru X3 - Mikazuki-jima Jiken no Shinsou (Japan).iso')
    args=parser.parse_args()
    exe = pilot.EVAL/'ee-pilot/build/ps2xRecomp/ps2_recomp.exe'
    begin=perf_counter()
    run=pilot.generate(args.iso,exe,entries=ENTRIES,work=WORK)
    pack(run,perf_counter()-begin)
