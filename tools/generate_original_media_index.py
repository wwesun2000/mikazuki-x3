"""Bind original image, movie and Vorbis resource names to DISC.FAD identities."""
import json
from pathlib import Path
from vm_handlers import Image

ROOT=Path(__file__).resolve().parents[1]
TYPES={'.ipu':6,'.pss':5,'.mmv':4,'.m2v':3,'.ogg':0,'.sab':10}


def virtual_name(elf,name):
    kind=TYPES[Path(name).suffix]
    pointer=elf.word(0x22acc8+kind*68+12)
    at=elf.offset(pointer)
    return elf.data[at:at+64].split(b'\0')[0].decode('ascii')+Path(name).name


def main():
    media=json.loads((ROOT/'analysis/fad_manifest.json').read_bytes())['archives'][0]
    if media['name']!='DISC.FAD':raise ValueError('Expected original main archive')
    elf=Image((ROOT/'local/extracted/SLPM_664.52').read_bytes())
    found={}
    for r in media['records']:
        if r['kind']!='file' or Path(r['path']).suffix not in TYPES:continue
        name=virtual_name(elf,r['path'])
        if name in found:raise ValueError(f'Ambiguous original virtual media filename: {name}')
        found[name]=[r['path'],r['sha256'],r['size']]
    h=['// Generated by tools/generate_original_media_index.py from DISC.FAD and the ELF type directory table.',
       '#pragma once','#include <algorithm>','#include <array>','#include <cstdint>','#include <string_view>',
       'namespace kx3::platform {','struct OriginalMediaBinding { const char *name,*path,*sha; std::uint32_t size; };',
       f'inline constexpr std::array<OriginalMediaBinding,{len(found)}> original_media = {{{{']
    h.extend('    {'+','.join(json.dumps(v) for v in [name,*values])+'},' for name,values in sorted(found.items()))
    h+=['}};','inline const OriginalMediaBinding* find_original_media(std::string_view name) noexcept {',
        '    const auto it=std::lower_bound(original_media.begin(),original_media.end(),name,',
        '        [](const OriginalMediaBinding& row,std::string_view n){return std::string_view(row.name)<n;});',
        '    return it!=original_media.end() && name==it->name ? &*it : nullptr;','}','}','']
    target=ROOT/'port/platform/original_media_catalog.hpp'
    target.write_text('\n'.join(h),encoding='utf-8')
    print(f'{len(found)} original media identities indexed')


if __name__=='__main__':main()
