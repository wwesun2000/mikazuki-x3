"""Generate the four original EE sound parameter conversion functions."""
import csv
import json
import struct
from pathlib import Path

from generate_expandband_recomp import INSTRUCTION, hash_bytes, save
import run_ps2recomp_pilot as pilot

entries = (0x1b0d38, 0x1d34d0, 0x1d3504, 0x1d3530)

def export(run, selected=entries, module='sound', driver='generate_sound_recomp.py', *, link_header=True):
    elf = (run / 'SLPM_664.52').read_bytes()
    if hash_bytes(elf)!=pilot.ELF_SHA:
        raise ValueError('Wrong game ELF')
    with (run/'functions.csv').open(newline='') as f:
        ends={int(row['Start'],16):int(row['End'],16) for row in csv.DictReader(f)}
    bodies, rows = [], []
    for address in selected:
        source = next((run / 'generated').glob(f'*_0x{address:x}.cpp')).read_bytes()
        body = source[source.index(b'// Function:'):]
        emitted=set()
        for pc, word in INSTRUCTION.findall(body):
            pc=int(pc,16)
            if not address<=pc<ends[address] or struct.unpack_from('<I',elf,pc-0xff000)[0]!=int(word,16):
                raise ValueError(f'Original instruction mismatch at {pc:#x}')
            emitted.add(pc)
        missing=sorted(set(range(address,ends[address],4))-emitted)
        if any(struct.unpack_from('<I',elf,pc-0xff000)[0] for pc in missing):
            raise ValueError(f'Missing nonzero original instruction in {address:#x}')
        bodies.append(body)
        rows.append(dict(entry=hex(address), generated_body_sha256=hash_bytes(body),
                         output_cpp_sha256=hash_bytes(source), end_exclusive=hex(ends[address]),
                         original_words=(ends[address]-address)//4, omitted_zero_nops=[hex(pc) for pc in missing]))
    header = f'// Generated by tools/{driver}.\n#pragma once\n\n'.encode() + b'\n'.join(bodies)
    destination=pilot.ROOT/'port/core' if link_header else run
    save(destination/f'{module}_generated.hpp', header)
    save(pilot.ROOT/f'analysis/ps2recomp-{module}/manifest.json', (json.dumps(
        dict(elf_sha256=hash_bytes(elf), header_sha256=hash_bytes(header), functions=rows), indent=2)+'\n').encode())

if __name__ == '__main__':
    iso = pilot.ROOT/'Kamaitachi no Yoru X3 - Mikazuki-jima Jiken no Shinsou (Japan).iso'
    export(pilot.generate(iso, pilot.EVAL/'ee-pilot/build/ps2xRecomp/ps2_recomp.exe',
                          entries=entries, work=pilot.ROOT/'local/pc-core/ps2recomp-sound'))
