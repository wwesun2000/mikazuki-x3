"""Emit only source-proven return-zero wrappers; never infer unknown handlers as NOP."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA = "50ba47014cf2def901d2cd0f2319459525631a6b27bc8a030ccb9a98b4f57160"


def main():
    source = (ROOT / "local/extracted/SLPM_664.52").read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
        raise ValueError("Original ELF identity mismatch")
    proof_path = ROOT / "analysis/ghidra/vm-shared-tail-review-v1/proof.json"
    proof_bytes = proof_path.read_bytes()
    proof = json.loads(proof_bytes)
    if proof["elf_sha256"] != SOURCE_SHA:
        raise ValueError("Proof ELF identity mismatch")
    entries = set()
    def verify(units, words):
        if len(units) != len(words):
            raise ValueError("Unexpected instruction count")
        for unit, word in zip(units, words):
            off = unit["file_offset"]
            if int(unit["raw_word"], 16) != word or source[off:off+4] != word.to_bytes(4, "little"):
                raise ValueError("Source instruction mismatch")
    for group in proof["groups"]:
        tail = int(group["tail_entry"], 16)
        verify(group["tail_instructions"], [0x03e00008, 0x0000102d])
        entries.add(tail)
        words = [0x27bdfff0, 0xffbf0000, 0xdfbf0000, 0x08000000 | (tail >> 2), 0x27bd0010]
        verify(group["owner_instructions"], words)
        entries.add(int(group["owner_before"]["entry"].split(":")[1], 16))
        for wrapper in group["rejected_wrappers"]:
            verify(wrapper["instructions"], words)
            entries.add(int(wrapper["entry"], 16))
    if len(entries) != 104:
        raise ValueError("Unexpected closed wrapper set")
    text = "// Generated by tools/generate_zero_bindings.py; source-verified, not unknown-opcode fallbacks.\n"
    text += "// ELF SHA256: " + SOURCE_SHA + "\n"
    text += "// Proof SHA256: " + hashlib.sha256(proof_bytes).hexdigest() + "\n"
    text += "#pragma once\n#include <array>\n#include <cstdint>\nnamespace kx3 {\n"
    text += "inline constexpr std::array<std::uint32_t, 104> zero_bindings = {\n"
    text += "".join(f"    0x{entry:08x},\n" for entry in sorted(entries))
    text += "};\n}\n"
    (ROOT / "port/core/zero_bindings.hpp").write_text(text, encoding="utf-8")
    print(f"Verified and emitted {len(entries)} original return-zero bindings")


if __name__ == "__main__":
    main()
